import NextAuth from 'next-auth';
import Google from 'next-auth/providers/google';

/**
 * Вход в админку.
 *
 * Своих паролей мы не храним вообще — за проверку личности отвечает Google.
 * Нам остаётся только решить, кого пускать: список разрешённых почт лежит
 * в переменной окружения ADMIN_EMAILS через запятую.
 *
 * Почему так, а не «регистрация с паролем»: тогда пришлось бы хранить хеши,
 * делать восстановление доступа, защищаться от подбора. Каждый из этих шагов
 * легко сделать неправильно, а цена ошибки — чужой человек в админке сайта.
 * Здесь ломать просто нечего: утечь нечему, подбирать нечего.
 */

const РАЗРЕШЁННЫЕ = (process.env.ADMIN_EMAILS ?? '')
    .split(',')
    .map((почта) => почта.trim().toLowerCase())
    .filter(Boolean);

export const { handlers, signIn, signOut, auth } = NextAuth({
    providers: [Google],

    callbacks: {
        /**
         * Вызывается после того, как Google подтвердил личность,
         * но ДО того, как человек попадёт внутрь. Вернём false — не пустит.
         */
        async signIn({ profile }) {
            const почта = profile?.email?.toLowerCase();

            // Нет почты — не пускаем
            if (!почта) return false;

            // Google не подтвердил, что почта принадлежит этому человеку.
            // Без этой проверки можно было бы завести аккаунт с чужим адресом
            // и войти под ним.
            if (!profile?.email_verified) return false;

            // Пусто в ADMIN_EMAILS — не пускаем никого.
            // Закрыто по умолчанию: забыть переменную безопаснее, чем
            // случайно открыть админку всему интернету.
            return РАЗРЕШЁННЫЕ.includes(почта);
        },
    },

    pages: {
        signIn: '/admin/login',
        error: '/admin/login',
    },
});
